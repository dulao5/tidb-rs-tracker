#!/bin/sh
# Rebuild the extraction DB from a TiDB checkout and the raw coverage:
#   load-raw.sh <tidb repo root> [db]          (db defaults to work/extract.db)
# Then `scripts/tracker.py export <db>` refreshes data/.
#
# Raw coverage, in load order:
#   work/covmap/      the full run: <pkg>.tsv per package.
#   work/covmap-fp/   re-runs with failpoints enabled (E3): <pkg>.tsv plus
#                     status/<pkg>.tsv. Every test named in a status file has
#                     its coverage and outcome replaced by the re-run's.
# A run directory's outcomes come from its status/*.tsv (pkg, test, status,
# detail). The first run predates status files: for it, failures are read
# from covmap logs in work/logs if present, and any test with coverage and no
# recorded failure is ok. All tests that failed or produced no coverage in
# that run were re-run in covmap-fp, so the logs are not needed to rebuild.
set -eu
repo=$1
root=$(cd "$(dirname "$0")/.." && pwd)
here=$root/work
db=${2:-$here/extract.db}
fp=${FP-$here/covmap-fp}   # FP= (empty) loads the full run only
commit=$(git -C "$repo" rev-parse HEAD)
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
(cd "$root" && go run ./cmd/inventory -repo "$repo" -commit "$commit") > "$tmp"
rm -f "$db"
sqlite3 "$db" <<SQL
.read $root/sql/extract.sql
CREATE TEMP TABLE raw(kind,repo,pkg,path,name,line,subtests,uses_store,uses_fp,stmts,base_commit);
.mode tabs
.import $tmp raw
INSERT INTO go_test(kind,repo,pkg,path,name,line,subtests,uses_store,uses_fp,stmts,base_commit)
SELECT kind,repo,pkg,path,name,NULLIF(line,'0'),subtests,uses_store,uses_fp,NULLIF(stmts,''),base_commit FROM raw;
SQL
sqlite3 "$db" "SELECT kind, count(*) FROM go_test GROUP BY kind;"

# Every function declared under pkg/ (not only the ones tests reach).
(cd "$root" && go run ./cmd/inventory -repo "$repo" -funcs) > "$tmp"
sqlite3 "$db" <<SQL
.mode tabs
.import $tmp go_func_decl
SQL
sqlite3 "$db" "SELECT 'declared funcs', generated, count(*), sum(lines) FROM go_func_decl GROUP BY generated;"

# load_cov <covmap tsv>: add its test -> func rows. Functions in files
# generated by failpoint-ctl (binding__failpoint_binding__.go) are dropped.
load_cov() {
  sqlite3 "$db" <<SQL
CREATE TEMP TABLE cov(pkg,test,file,func);
.mode tabs
.import $1 cov
DELETE FROM cov WHERE file LIKE '%\_\_failpoint\_%' ESCAPE '\\';
INSERT OR IGNORE INTO go_func(file,name) SELECT DISTINCT file,func FROM cov;
INSERT OR IGNORE INTO test_func(test_id,func_id)
SELECT t.id, f.id FROM cov c
JOIN go_test t ON t.kind='unit' AND t.pkg=c.pkg AND t.name=c.test
JOIN go_func f ON f.file=c.file AND f.name=c.func;
SQL
}

# load_status <status tsv>: set the outcome of the tests in it.
load_status() {
  sqlite3 "$db" <<SQL
CREATE TEMP TABLE st(pkg,test,status,detail);
.mode tabs
.import $1 st
INSERT OR REPLACE INTO cov_status(test_id,status,detail)
SELECT DISTINCT t.id, s.status, NULLIF(s.detail,'') FROM st s
JOIN go_test t ON t.kind='unit' AND t.pkg=s.pkg AND t.name=s.test;
SQL
}

# 1. The full run.
for f in "$here"/covmap/*.tsv; do
  [ -e "$f" ] && load_cov "$f"
done
for f in "$here"/covmap/status/*.tsv; do
  [ -e "$f" ] && load_status "$f"
done
# Legacy outcome from the covmap logs ("<Test>: exit status N").
: > "$tmp"
for f in "$here"/covmap/*.tsv; do
  b=$(basename "$f" .tsv)
  pkg=$(head -n 1 "$f" | cut -f1)
  [ -n "$pkg" ] || continue
  [ -e "$here/covmap/status/$b.tsv" ] && continue
  grep -oE '(Test[A-Za-z0-9_]+): (exit status [0-9]+|signal: [a-z ]+)' "$here/logs/$b.log" 2>/dev/null |
    awk -v pkg="$pkg" -F': ' '{print pkg "\t" $1 "\tfailed\t" $2}' >> "$tmp" || true
done
load_status "$tmp"
sqlite3 "$db" "INSERT OR IGNORE INTO cov_status(test_id,status) SELECT DISTINCT test_id,'ok' FROM test_func;"
sqlite3 "$db" "SELECT 'full run', status, count(*) FROM cov_status GROUP BY status;"

# 2. Re-runs: replace coverage and outcome of every test they name.
if [ -n "$fp" ] && [ -d "$fp/status" ]; then
  # sqlite's tab import treats " as quoting; details are free text.
  cat "$fp"/status/*.tsv | tr '"' "'" > "$tmp"
  sqlite3 "$db" <<SQL
CREATE TEMP TABLE st(pkg,test,status,detail);
.mode tabs
.import $tmp st
DELETE FROM test_func WHERE test_id IN
  (SELECT t.id FROM st s JOIN go_test t ON t.kind='unit' AND t.pkg=s.pkg AND t.name=s.test);
SQL
  for f in "$fp"/*.tsv; do
    [ -e "$f" ] && load_cov "$f"
  done
  load_status "$tmp"
  sqlite3 "$db" "DELETE FROM go_func WHERE id NOT IN (SELECT func_id FROM test_func);"
  echo "failpoint re-run: $(wc -l < "$tmp") tests"
fi

sqlite3 "$db" "SELECT 'mapped tests', count(DISTINCT test_id), 'funcs', count(DISTINCT func_id) FROM test_func;"
sqlite3 "$db" "SELECT status, count(*) FROM cov_status GROUP BY status;"
sqlite3 "$db" < "$root/sql/derive_features.sql"
sqlite3 "$db" "SELECT count(*) AS features, (SELECT count(*) FROM test_feature) AS links FROM feature;"

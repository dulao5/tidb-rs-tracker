#!/usr/bin/env python3
"""Blocks ported in parts, and the boundary stubs that stand for the rest (tidb-rs VS1-03).

tidb-rs ports some blocks in parts (tidb-rs `specs/VS1-vertical-slice/plan.md` §0 item 3, as
D06.2 / D06.3 "part 1"): a part converges on its own function list (tidb-rs
`scripts/converge.py --part`), and the block's other functions are boundary stubs
(constitution §4.3) until their part is ported. This script keeps the three data files:

- data/block_parts.tsv (hand-maintained): the parts of each block: `block`, `part`, `item`
  (the tidb-rs work item, e.g. VS1-10, if any), `status` (planned / in-progress / done),
  `evidence` (PRs, converge count).
- data/part_funcs.tsv (generated by `import`): the Go functions of each part (`block`,
  `part`, `file`, `symbol`), from a part function list such as tidb-rs
  specs/VS1-vertical-slice/functions.tsv.
- data/stubs.tsv: the boundary stubs in tidb-rs (`file`, `symbol`, `block`, `kind`, `note`):
  `kind` is temporary (blocked-by:<block>, must vanish when the block is done), permanent
  (an exception or a "not ported" decision) or delegated (left to Go TiDB in the cluster).
  `scan --write` rebuilds the (file, symbol, block) rows from a tidb-rs checkout and keeps
  `kind` / `note`; `scan` alone fails if the registry and the code differ. `check` fails on
  an empty `note`. `.gitattributes` merges stubs.tsv with the union driver, so a merge keeps
  both sides' rows (and notes); run `scan --write` afterwards to drop the stale ones.

    parts.py import ../tidb-rs/specs/VS1-vertical-slice/functions.tsv
    parts.py scan [--write] ../tidb-rs
    parts.py check            # validate the three files; fail if reports/parts.md is stale
    parts.py report           # reports/parts.md
"""

import argparse
import collections
import csv
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(ROOT, "data")
REPORT = os.path.join(ROOT, "reports", "parts.md")

PARTS_COLS = ["block", "part", "item", "status", "evidence"]
PART_FUNCS_COLS = ["block", "part", "file", "symbol"]
STUBS_COLS = ["file", "symbol", "block", "kind", "note"]
STATUSES = ("planned", "in-progress", "done")
KINDS = ("temporary", "permanent", "delegated")

# `blocked-by:D06.2`, `blocked-by D00.2`, `blocked-by:D08.6, D08.7` in a comment, and
# `blocked("D05.3", ...)` (tidb_base::blocked) in code.
BLOCK_ID = r"(?:D\d+\.\d+|EXC\.[A-Z]+|X|DEF\.[A-Z]+)"
COMMENT_RE = re.compile(r"//.*blocked-by[: ]\s*(" + BLOCK_ID + r"(?:\s*,\s*" + BLOCK_ID + r")*)")
CALL_RE = re.compile(r"\bblocked\(\s*\"(" + BLOCK_ID + r")\"")
FN_RE = re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)?(?:const\s+)?(?:async\s+)?(?:unsafe\s+)?fn\s+(\w+)")


def die(msg):
    sys.exit("parts: " + msg)


def read(name, cols):
    path = os.path.join(DATA, name)
    with open(path, encoding="utf-8", newline="") as f:
        rows = list(csv.reader(f, delimiter="\t"))
    if not rows or rows[0] != cols:
        die(f"{name}: header {rows[0] if rows else None} != {cols}")
    for n, r in enumerate(rows[1:], 2):
        if len(r) != len(cols):
            die(f"{name}:{n}: {len(r)} fields, want {len(cols)}")
    return [dict(zip(cols, r)) for r in rows[1:]]


def write(name, cols, rows):
    rows = sorted(rows, key=lambda r: [r[c] for c in cols])
    with open(os.path.join(DATA, name), "w", encoding="utf-8", newline="\n") as f:
        f.write("\t".join(cols) + "\n")
        for r in rows:
            f.write("\t".join(r[c] for c in cols) + "\n")


def tsv(name):
    with open(os.path.join(DATA, name), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


# ---------------------------------------------------------------- import


def cmd_import(args):
    rows = []
    with open(args.functions, encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f, delimiter="\t"):
            rows.append({"block": r["block"], "part": r["item"], "file": r["file"], "symbol": r["function"]})
    keep = [r for r in read("part_funcs.tsv", PART_FUNCS_COLS)
            if r["part"] not in {x["part"] for x in rows}] if os.path.exists(
        os.path.join(DATA, "part_funcs.tsv")) else []
    write("part_funcs.tsv", PART_FUNCS_COLS, keep + rows)
    print(f"part_funcs.tsv: {len(rows)} functions of {len({r['part'] for r in rows})} parts imported")


# ---------------------------------------------------------------- scan


ITEM_RE = re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)?(?:const\s+|async\s+|unsafe\s+)*(?:fn|mod|struct|enum|const|static)\s+(\w+)")


def next_item(lines, i):
    """The name of the item a comment block ending above line `i` annotates, or None when the
    comment is followed by code (it sits inside a body)."""
    while i < len(lines):
        t = lines[i].strip()
        if not t or t.startswith("//") or t.startswith("#["):
            i += 1
            continue
        m = ITEM_RE.match(lines[i])
        return m.group(1) if m else None
    return None


def scan_stubs(tidb_rs):
    """(file, symbol, block) of every boundary stub in tidb-rs's Rust sources (crates/,
    without the spike crates and tests)."""
    out = set()
    crates = os.path.join(tidb_rs, "crates")
    for dirpath, dirnames, filenames in os.walk(crates):
        rel_dir = os.path.relpath(dirpath, tidb_rs)
        dirnames[:] = [d for d in dirnames if d not in ("spike", "tests", "target")]
        for fn in sorted(filenames):
            if not fn.endswith(".rs") or fn in ("tests.rs",) or fn.endswith("_tests.rs"):
                continue
            path = os.path.join(dirpath, fn)
            rel = os.path.join(rel_dir, fn)
            lines = open(path, encoding="utf-8").read().splitlines()
            in_test = False
            last_fn = "(module)"
            for i, line in enumerate(lines):
                if line.startswith("#[cfg(test)]"):
                    in_test = True
                if in_test:
                    continue
                m = FN_RE.match(line)
                if m:
                    last_fn = m.group(1)
                    continue
                if line.lstrip().startswith("//"):
                    c = COMMENT_RE.search(line)
                    if c and "glue:" in line:
                        # An annotation above an item names that item; inside a body, the
                        # enclosing fn.
                        target = next_item(lines, i + 1) or last_fn
                        for b in c.group(1).split(","):
                            out.add((rel, target, b.strip()))
                    continue
                for b in CALL_RE.findall(line):
                    out.add((rel, last_fn, b))
    return out


def cmd_scan(args):
    found = scan_stubs(args.tidb_rs)
    path = os.path.join(DATA, "stubs.tsv")
    old = read("stubs.tsv", STUBS_COLS) if os.path.exists(path) else []
    by_key = {(r["file"], r["symbol"], r["block"]): r for r in old}
    if args.write:
        rows = [by_key.get(k, {"file": k[0], "symbol": k[1], "block": k[2], "kind": "temporary", "note": ""})
                for k in found]
        write("stubs.tsv", STUBS_COLS, rows)
        print(f"stubs.tsv: {len(rows)} stubs ({len(found - set(by_key))} new, "
              f"{len(set(by_key) - found)} removed)")
        return
    missing = sorted(found - set(by_key))
    gone = sorted(set(by_key) - found)
    for k in missing:
        print(f"not registered: {k[0]} {k[1]} blocked-by:{k[2]}")
    for k in gone:
        print(f"registered but not in the code: {k[0]} {k[1]} blocked-by:{k[2]}")
    if missing or gone:
        die("data/stubs.tsv differs from the code: run scripts/blocks/parts.py scan --write <tidb-rs>")
    print(f"stubs.tsv matches the code: {len(found)} stubs")


# ---------------------------------------------------------------- check / report


def validate():
    errors = []
    blocks = {r["block"] for r in tsv("blocks.tsv")}
    done = {r["block"] for r in tsv("blocks_done.tsv")}
    func_block = {}
    for r in tsv("func_blocks.tsv"):
        func_block[(r["file"], r["symbol"])] = r["block"]
    parts = read("block_parts.tsv", PARTS_COLS)
    part_funcs = read("part_funcs.tsv", PART_FUNCS_COLS)
    stubs = read("stubs.tsv", STUBS_COLS)
    for name, rows, cols in (("block_parts.tsv", parts, PARTS_COLS), ("part_funcs.tsv", part_funcs, PART_FUNCS_COLS),
                             ("stubs.tsv", stubs, STUBS_COLS)):
        keys = [[r[c] for c in cols] for r in rows]
        if keys != sorted(keys):
            errors.append(f"{name}: rows not sorted")
    seen = set()
    for r in parts:
        if r["block"] not in blocks:
            errors.append(f"block_parts.tsv: unknown block {r['block']}")
        if r["status"] not in STATUSES:
            errors.append(f"block_parts.tsv: {r['block']} {r['part']}: status {r['status']!r} not in {STATUSES}")
        if (r["block"], r["part"]) in seen:
            errors.append(f"block_parts.tsv: duplicate part {r['block']} {r['part']}")
        seen.add((r["block"], r["part"]))
    for r in part_funcs:
        if (r["block"], r["part"]) not in seen:
            errors.append(f"part_funcs.tsv: {r['block']} {r['part']} is not in block_parts.tsv")
        actual = func_block.get((r["file"], r["symbol"]))
        if actual is None:
            errors.append(f"part_funcs.tsv: {r['file']} {r['symbol']} is not in func_blocks.tsv")
        elif actual != r["block"]:
            errors.append(f"part_funcs.tsv: {r['file']} {r['symbol']} belongs to {actual}, not {r['block']}")
    dup = [k for k, n in collections.Counter((r["file"], r["symbol"]) for r in part_funcs).items() if n > 1]
    for k in dup:
        errors.append(f"part_funcs.tsv: {k[0]} {k[1]} is in more than one part")
    for r in stubs:
        if r["block"] not in blocks:
            errors.append(f"stubs.tsv: {r['file']} {r['symbol']}: unknown block {r['block']}")
        if r["kind"] not in KINDS:
            errors.append(f"stubs.tsv: {r['file']} {r['symbol']}: kind {r['kind']!r} not in {KINDS}")
        # Every stub says why it exists; an empty note usually means a merge rescan lost it.
        if not r["note"].strip():
            errors.append(f"stubs.tsv: {r['file']} {r['symbol']}: empty note (say what the stub "
                          f"waits for; after a merge, take the note from the branch that added it)")
        # Constitution §4.3: a temporary stub disappears when its block is done.
        if r["kind"] == "temporary" and r["block"] in done:
            errors.append(f"stubs.tsv: {r['file']} {r['symbol']}: temporary stub on {r['block']}, "
                          f"which is done (data/blocks_done.tsv)")
    return errors, parts, part_funcs, stubs


def render(parts, part_funcs, stubs):
    lines = {}
    for r in tsv("go_funcs.tsv"):
        if r["generated"] == "0":
            lines[(r["file"], r["symbol"])] = lines.get((r["file"], r["symbol"]), 0) + int(r["lines"])
    total = collections.Counter()
    for r in tsv("func_blocks.tsv"):
        total[r["block"]] += 1
    n_funcs, n_lines = collections.Counter(), collections.Counter()
    for r in part_funcs:
        n_funcs[(r["block"], r["part"])] += 1
        n_lines[(r["block"], r["part"])] += lines.get((r["file"], r["symbol"]), 0)
    out = ["# Blocks ported in parts, and boundary stubs", "",
           "Generated by `scripts/blocks/parts.py report` from data/block_parts.tsv, data/part_funcs.tsv "
           "and data/stubs.tsv. Do not edit.", "",
           "A part converges on its own functions (tidb-rs `scripts/converge.py --part`); the rest of "
           "the block is `blocked-by:<block>` until its part is ported.", "",
           "## Parts", "",
           "| block | part | item | status | functions (of block) | Go lines | evidence |",
           "|---|---|---|---|--:|--:|---|"]
    for r in parts:
        k = (r["block"], r["part"])
        fn = f"{n_funcs[k]} / {total[r['block']]}" if n_funcs[k] else "—"
        ln = str(n_lines[k]) if n_funcs[k] else "—"
        out.append(f"| {r['block']} | {r['part']} | {r['item'] or '—'} | {r['status']} | {fn} | {ln} | "
                   f"{r['evidence'] or ''} |")
    by_block = collections.defaultdict(collections.Counter)
    for r in stubs:
        by_block[r["block"]][r["kind"]] += 1
    out += ["", "## Boundary stubs by block", "",
            f"{len(stubs)} stubs in tidb-rs (`scan` keeps data/stubs.tsv in step with the code).", "",
            "| block | temporary | permanent | delegated |", "|---|--:|--:|--:|"]
    for b in sorted(by_block):
        c = by_block[b]
        out.append(f"| {b} | {c['temporary']} | {c['permanent']} | {c['delegated']} |")
    return "\n".join(out) + "\n"


def cmd_check(args):
    errors, parts, part_funcs, stubs = validate()
    text = render(parts, part_funcs, stubs)
    old = open(REPORT, encoding="utf-8").read() if os.path.exists(REPORT) else None
    if old != text:
        errors.append("reports/parts.md is stale: run scripts/blocks/parts.py report")
    if errors:
        die("\n  ".join(["check failed:"] + errors))
    print(f"parts check ok: {len(parts)} parts, {len(part_funcs)} part functions, {len(stubs)} stubs")


def cmd_report(args):
    errors, parts, part_funcs, stubs = validate()
    if errors:
        die("\n  ".join(["invalid data:"] + errors))
    with open(REPORT, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(parts, part_funcs, stubs))
    print(f"wrote {os.path.relpath(REPORT, ROOT)}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("import", help="part function list -> data/part_funcs.tsv")
    p.add_argument("functions")
    p.set_defaults(func=cmd_import)
    p = sub.add_parser("scan", help="compare data/stubs.tsv with the stubs in a tidb-rs checkout")
    p.add_argument("--write", action="store_true", help="rewrite data/stubs.tsv from the code")
    p.add_argument("tidb_rs")
    p.set_defaults(func=cmd_scan)
    sub.add_parser("check").set_defaults(func=cmd_check)
    sub.add_parser("report").set_defaults(func=cmd_report)
    args = ap.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()

package main

// Tables of block D01.9 (pkg/util/collate, crates/types) and of the part of
// pkg/parser/charset it uses (crates/parser):
//
//   - general_ci planes (collate/general_ci.go) and the gbk_chinese_ci sort keys
//     (collate/gbk_chinese_ci_data.go): unexported package-level literals, read from
//     the Go AST (values from go/types);
//   - the UCA tables ucadata.DUCET0400Table / DUCET0900Table: exported, dumped from
//     the run-time values of the linked package;
//   - parser/charset's `collations` slice and `charsets` map: AST;
//   - the GBK encoder of golang.org/x/text (simplifiedchinese.GBK), which TiDB's
//     customGBK wraps: its five encode tables, as one table over the BMP, from the
//     run-time encoder (one call per rune).
//
// Every table is cross-checked by the govec domain "collate" (key and compare
// digests over all code points), so a generator bug shows up as a vector mismatch.

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/constant"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode/utf8"

	"github.com/pingcap/tidb/pkg/util/collate/ucadata"
	"golang.org/x/text/encoding/simplifiedchinese"
)

func rsHeader(e *emitter, domain string, goFiles ...string) {
	e.p("// Code generated by tidb-rs-tracker govec/cmd/rsgen from TiDB v8.5.8. DO NOT EDIT.\n")
	e.p("// Regenerate: (cd govec && go run ./cmd/rsgen -types <tidb-rs>/crates/types/src -parser <tidb-rs>/crates/parser/src)\n")
	e.p("// Verified by the govec domain %q (tests/govec_%s.rs).\n\n", domain, domain)
	for _, f := range goFiles {
		e.p("//! go-file: %s\n", f)
	}
	e.p("\n// Generated data keeps Go's identifiers (mapping rule M-GONAME).\n#![allow(non_upper_case_globals)]\n\n")
}

func writeTo(dir, rel string, e *emitter) {
	path := filepath.Join(dir, rel)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		panic(err)
	}
	if err := os.WriteFile(path, e.buf.Bytes(), 0o644); err != nil {
		panic(err)
	}
	fmt.Fprintf(os.Stderr, "rsgen: wrote %s (%d bytes)\n", path, e.buf.Len())
}

// array emits `vals` as the body of a Rust array literal, perLine per line.
func array(e *emitter, vals []string, perLine int) {
	for i := 0; i < len(vals); i += perLine {
		j := min(i+perLine, len(vals))
		e.p("    %s,\n", strings.Join(vals[i:j], ", "))
	}
}

func constUint(p *pkg, x ast.Expr) uint64 {
	tv, ok := p.info.Types[x]
	if !ok || tv.Value == nil {
		panic(fmt.Sprintf("rsgen: not a constant at %v", p.fset.Position(x.Pos())))
	}
	v, exact := constant.Uint64Val(constant.ToInt(tv.Value))
	if !exact {
		panic(fmt.Sprintf("rsgen: not a uint64 at %v", p.fset.Position(x.Pos())))
	}
	return v
}

func hexs(vs []uint64) []string {
	out := make([]string, len(vs))
	for i, v := range vs {
		out[i] = fmt.Sprintf("0x%X", v)
	}
	return out
}

// genCollateTables writes the collate tables under dir (crates/types/src).
func genCollateTables(dir string) {
	tidbDir := modDir("github.com/pingcap/tidb")
	cp := load(filepath.Join(tidbDir, "pkg", "util", "collate"))

	// general_ci: planeXX and planeTable.
	{
		e := &emitter{}
		rsHeader(e, "collate", "pkg/util/collate/general_ci.go")
		_, tbl := findVar(cp, "general_ci.go", "planeTable")
		var refs []string
		planes := map[string]bool{}
		for _, el := range tbl.Elts {
			id := el.(*ast.Ident).Name
			if id == "nil" {
				refs = append(refs, "None")
				continue
			}
			refs = append(refs, "Some(&"+id+")")
			planes[id] = true
		}
		if len(refs) != 256 {
			panic(fmt.Sprintf("rsgen: planeTable has %d entries", len(refs)))
		}
		var names []string
		for n := range planes {
			names = append(names, n)
		}
		sort.Strings(names)
		for _, n := range names {
			_, cl := findVar(cp, "general_ci.go", n)
			if len(cl.Elts) != 256 {
				panic("rsgen: " + n + " is not 256 entries")
			}
			var vs []uint64
			for _, el := range cl.Elts {
				vs = append(vs, constUint(cp, el))
			}
			e.p("pub(crate) static %s: [u16; 256] = [\n", n)
			array(e, hexs(vs), 16)
			e.p("];\n\n")
		}
		e.p("pub(crate) static planeTable: [Option<&[u16; 256]>; 256] = [\n")
		array(e, refs, 8)
		e.p("];\n")
		writeTo(dir, "collate/general_ci_data.rs", e)
	}

	// gbk_chinese_ci: gbkChineseCISortKeyTable.
	{
		e := &emitter{}
		rsHeader(e, "collate", "pkg/util/collate/gbk_chinese_ci_data.go")
		_, cl := findVar(cp, "gbk_chinese_ci_data.go", "gbkChineseCISortKeyTable")
		if len(cl.Elts) != 0x10000 {
			panic(fmt.Sprintf("rsgen: gbkChineseCISortKeyTable has %d entries", len(cl.Elts)))
		}
		var vs []uint64
		for _, el := range cl.Elts {
			vs = append(vs, constUint(cp, el))
		}
		e.p("pub(crate) static gbkChineseCISortKeyTable: [u16; 0xFFFF + 1] = [\n")
		array(e, hexs(vs), 16)
		e.p("];\n")
		writeTo(dir, "collate/gbk_chinese_ci_data.rs", e)
	}

	// ucadata: DUCET0400Table, DUCET0900Table (run-time values).
	uca := func(file, name, goFile, src string, mt []uint64, lrm map[rune][2]uint64) {
		e := &emitter{}
		rsHeader(e, "collate", goFile)
		e.p("use super::DucetTable;\n\n")
		e.p("/// %s is the collation element table for the corresponding unicode version.\n", name)
		e.p("/// it's generated from %s\n", src)
		e.p("pub static %s: DucetTable = DucetTable {\n", name)
		e.p("    map_table4: &%s_MapTable4,\n", name)
		e.p("    long_rune_map: &%s_LongRuneMap,\n", name)
		e.p("};\n\n")
		e.p("static %s_MapTable4: [u64; %d] = [\n", name, len(mt))
		array(e, hexs(mt), 8)
		e.p("];\n\n")
		keys := make([]int, 0, len(lrm))
		for k := range lrm {
			keys = append(keys, int(k))
		}
		sort.Ints(keys)
		e.p("/// Go `map[rune][2]uint64`; entries sorted by rune (generated).\n")
		e.p("static %s_LongRuneMap: [(u32, [u64; 2]); %d] = [\n", name, len(keys))
		for _, k := range keys {
			v := lrm[rune(k)]
			e.p("    (0x%X, [0x%X, 0x%X]),\n", k, v[0], v[1])
		}
		e.p("];\n")
		writeTo(dir, file, e)
	}
	uca("collate/ucadata/unicode_ci_data.rs", "DUCET0400Table",
		"pkg/util/collate/ucadata/unicode_ci_data_generated.go",
		"https://www.unicode.org/Public/UCA/4.0.0/allkeys-4.0.0.txt",
		ucadata.DUCET0400Table.MapTable4[:], ucadata.DUCET0400Table.LongRuneMap)
	uca("collate/ucadata/unicode_0900_ai_ci_data.rs", "DUCET0900Table",
		"pkg/util/collate/ucadata/unicode_0900_ai_ci_data_generated.go",
		"https://www.unicode.org/Public/UCA/9.0.0/allkeys.txt",
		ucadata.DUCET0900Table.MapTable4[:], ucadata.DUCET0900Table.LongRuneMap)
}

// genCharsetTables writes parser/charset's tables and the GBK encode table
// under dir (crates/parser/src).
func genCharsetTables(dir string) {
	parserDir := modDir("github.com/pingcap/tidb/pkg/parser")
	p := load(filepath.Join(parserDir, "charset"))

	str := func(x ast.Expr) string {
		switch t := x.(type) {
		case *ast.Ident:
			if t.Name == "PadSpace" || t.Name == "PadNone" {
				return t.Name
			}
		}
		tv, ok := p.info.Types[x]
		if !ok || tv.Value == nil || tv.Value.Kind() != constant.String {
			panic(fmt.Sprintf("rsgen: not a string constant at %v", p.fset.Position(x.Pos())))
		}
		return rustStr(constant.StringVal(tv.Value))
	}
	num := func(x ast.Expr) string { return fmt.Sprint(constUint(p, x)) }

	e := &emitter{}
	rsHeader(e, "collate", "pkg/parser/charset/charset.go")
	e.p("use super::{CharsetDef, CollationDef, PadNone, PadSpace};\n\n")

	vs, cl := findVar(p, "charset.go", "collations")
	rustDoc(e, "", vs.Doc)
	e.p("pub(super) static collations: [CollationDef; %d] = [\n", len(cl.Elts))
	for _, el := range cl.Elts {
		f := el.(*ast.CompositeLit).Elts
		if len(f) != 6 {
			panic("rsgen: collation literal with != 6 fields")
		}
		isDefault := f[3].(*ast.Ident).Name
		e.p("    CollationDef { id: %s, charset_name: %s, name: %s, is_default: %s, sortlen: %s, pad_attribute: %s },\n",
			num(f[0]), str(f[1]), str(f[2]), isDefault, num(f[4]), str(f[5]))
	}
	e.p("];\n\n")

	vs, cl = findVar(p, "charset.go", "charsets")
	type cs struct{ key, name, defColl, desc, maxlen string }
	var css []cs
	for _, el := range cl.Elts {
		ke := el.(*ast.KeyValueExpr)
		c := cs{key: str(ke.Key)}
		for _, fe := range ke.Value.(*ast.CompositeLit).Elts {
			kv := fe.(*ast.KeyValueExpr)
			switch kv.Key.(*ast.Ident).Name {
			case "Name":
				c.name = str(kv.Value)
			case "DefaultCollation":
				c.defColl = str(kv.Value)
			case "Desc":
				c.desc = str(kv.Value)
			case "Maxlen":
				c.maxlen = num(kv.Value)
			case "Collations":
			default:
				panic("rsgen: unknown Charset field")
			}
		}
		css = append(css, c)
	}
	sort.Slice(css, func(i, j int) bool { return css[i].key < css[j].key })
	rustDoc(e, "", vs.Doc)
	e.p("///\n/// Go `map` literal; entries sorted by key (generated). `Collations` starts empty.\n")
	e.p("pub(super) static charsets: [(&str, CharsetDef); %d] = [\n", len(css))
	for _, c := range css {
		e.p("    (%s, CharsetDef { name: %s, default_collation: %s, desc: %s, maxlen: %s }),\n",
			c.key, c.name, c.defColl, c.desc, c.maxlen)
	}
	e.p("];\n")
	writeTo(dir, "gocharset/charset_data.rs", e)

	// GBK: x/text's encode tables over the BMP, from the run-time encoder.
	ge := &emitter{}
	rsHeader(ge, "collate")
	ge.p("//! The encode tables of golang.org/x/text@v0.39.0/encoding/simplifiedchinese (tables.go:\n")
	ge.p("//! encode0 .. encode4, indexed by rune within [encodeNLow, encodeNHigh)), as one table over\n")
	ge.p("//! the BMP: the two GBK bytes (big endian) of each rune, 0 where there is none. Generated by\n")
	ge.p("//! calling `simplifiedchinese.GBK.NewEncoder()` on every rune; runes above the BMP have no\n")
	ge.p("//! two-byte GBK code (checked by the generator).\n\n")
	var tbl [0x10000]uint64
	enc := simplifiedchinese.GBK.NewEncoder()
	for r := rune(0x80); r <= utf8.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		b, err := enc.Bytes([]byte(string(r)))
		if err != nil {
			continue
		}
		switch {
		case r == '€' && bytes.Equal(b, []byte{0x80}):
			// written as one byte by the encoder itself (Code Page 936)
		case len(b) == 2 && r < 0x10000:
			tbl[r] = uint64(b[0])<<8 | uint64(b[1])
		default:
			panic(fmt.Sprintf("rsgen: GBK encodes %U as %x", r, b))
		}
	}
	ge.p("pub(crate) static gbkEncode: [u16; 0x10000] = [\n")
	array(ge, hexs(tbl[:]), 16)
	ge.p("];\n")
	writeTo(dir, "gocharset/gbk_encode_data.rs", ge)
}

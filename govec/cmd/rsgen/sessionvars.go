// sessionVarsExcluded are scalar fields of SessionVars that only serve writes done by Go
// TiDB (D05.2 scoping, tracker rules.py): not generated.
var sessionVarsExcluded = map[string]bool{
	"DDLReorgPriority": true, "DMLBatchSize": true, "RetryLimit": true, "DisableTxnAutoRetry": true,
	"ShardAllocateStep": true, "AllowAutoRandExplicitInsert": true, "AllowRemoveAutoInc": true,
	"BatchInsert": true, "BatchDelete": true, "BatchCommit": true, "BulkDMLEnabled": true,
}

type svField struct {
	name, goType, rustType, value string
	doc                           *ast.CommentGroup
	via                           string // embedded struct it is promoted from
}

// genSessionVarsFields writes variable/session_fields.rs: the scalar fields of
// SessionVars (bool, integers, floats, strings, time.Duration and named types of those
// kinds, including fields promoted from embedded structs) with the values a fresh
// NewSessionVars(nil) holds. Pointers, maps, slices, interfaces, funcs, atomics and other
// structs are hand-written (session.rs); their names are listed in the file trailer.
func genSessionVarsFields(outDir string) {
	vdir := filepath.Join(modDir("github.com/pingcap/tidb"), "pkg", "sessionctx", "variable")
	p := load(vdir)
	docs := map[string]map[string]*ast.CommentGroup{}
	for _, f := range p.files {
		ast.Inspect(f, func(n ast.Node) bool {
			ts, ok := n.(*ast.TypeSpec)
			if !ok {
				return true
			}
			st, ok := ts.Type.(*ast.StructType)
			if !ok {
				return true
			}
			m := map[string]*ast.CommentGroup{}
			for _, fl := range st.Fields.List {
				d := fl.Doc
				if d == nil {
					d = fl.Comment
				}
				for _, nm := range fl.Names {
					m[nm.Name] = d
				}
			}
			docs[ts.Name.Name] = m
			return true
		})
	}
	sv := variable.NewSessionVars(nil)
	var fields, other []svField
	var walk func(v reflect.Value, t reflect.Type, via string)
	walk = func(v reflect.Value, t reflect.Type, via string) {
		for i := 0; i < t.NumField(); i++ {
			sf := t.Field(i)
			fv := v.Field(i)
			if sf.Anonymous && sf.Type.Kind() == reflect.Struct && sf.Type.PkgPath() == t.PkgPath() {
				walk(fv, sf.Type, sf.Name)
				continue
			}
			f := svField{name: sf.Name, goType: sf.Type.String(), doc: docs[t.Name()][sf.Name], via: via}
			if sessionVarsExcluded[sf.Name] {
				continue
			}
			rt, val, ok := rustScalar(fv, sf.Type)
			if !ok {
				other = append(other, f)
				continue
			}
			f.rustType, f.value = rt, val
			fields = append(fields, f)
		}
	}
	walk(reflect.ValueOf(sv).Elem(), reflect.TypeOf(*sv), "")

	var e emitter
	domainName = "sessionvars"
	e.p("// Code generated by tidb-rs-tracker govec/cmd/rsgen from TiDB v8.5.8. DO NOT EDIT.\n")
	e.p("// Regenerate: (cd govec && go run ./cmd/rsgen -sessionvars <tidb-rs>/crates/sessionctx/src), then cargo fmt\n")
	e.p("// Verified by the govec domain \"sessionvars\" (op `fresh`).\n//\n")
	e.p("//! go-file: pkg/sessionctx/variable/session.go\n\n")
	e.p("#![allow(non_upper_case_globals)]\n\n")
	e.p("/// The scalar fields of `SessionVars` (D05.2 T2): Go's names in snake case, Go's types\n")
	e.p("/// (named integer types as their underlying width, `time.Duration` as nanoseconds).\n")
	e.p("/// Fields promoted from an embedded struct (`Concurrency`, `MemQuota`, `BatchSize`, …)\n")
	e.p("/// are flattened, as Go code reads them through the outer struct.\n")
	e.p("#[derive(Clone, Debug, PartialEq)]\npub struct SessionVarsFields {\n")
	for _, f := range fields {
		rustDoc(&e, "    ", f.doc)
		origin := f.name
		if f.via != "" {
			origin = f.via + "." + f.name
		}
		e.p("    /// Go: `%s %s`\n", origin, f.goType)
		e.p("    pub %s: %s,\n", rustField(f.name), f.rustType)
	}
	e.p("}\n\n")
	e.p("impl Default for SessionVarsFields {\n")
	e.p("    /// The values of a fresh `NewSessionVars(nil)` with the default config.\n")
	e.p("    // go: NewSessionVars L2 (scalar fields; the others are built in session.rs)\n")
	e.p("    fn default() -> Self {\n        SessionVarsFields {\n")
	for _, f := range fields {
		e.p("            %s: %s,\n", rustField(f.name), f.value)
	}
	e.p("        }\n    }\n}\n\n")
	e.p("/// Names of the scalar fields, in declaration order (the govec `fresh` op dumps these).\n")
	e.p("pub const SCALAR_FIELDS: &[&str] = &[\n")
	for _, f := range fields {
		e.p("    %s,\n", rustStr(f.name))
	}
	e.p("];\n\n")
	e.p("// Non-scalar fields, hand-written in session.rs (D05.2 T2/T6) or X:\n")
	for _, f := range other {
		e.p("// - %s %s\n", f.name, f.goType)
	}
	saved := *out
	*out = outDir
	e.write("variable/session_fields.rs")
	*out = saved
	fmt.Fprintf(os.Stderr, "rsgen: %d scalar SessionVars fields, %d hand-written\n", len(fields), len(other))
}

var sessionVarsSnake = map[string]string{
	"Enable3StageDistinctAgg":      "enable_3stage_distinct_agg",
	"Enable3StageMultiDistinctAgg": "enable_3stage_multi_distinct_agg",
	"DefaultCollationForUTF8MB4":   "default_collation_for_utf8mb4",
	"TopNCostFactor":               "topn_cost_factor",
}

func rustField(goName string) string {
	s := snake(goName)
	if o, ok := sessionVarsSnake[goName]; ok {
		s = o
	}
	switch s {
	case "type", "match", "ref", "mod", "loop", "move", "use", "fn", "impl", "self", "crate", "super":
		return "r#" + s
	}
	return s
}

// rustScalar maps a scalar Go value to a Rust type and literal.
func rustScalar(v reflect.Value, t reflect.Type) (string, string, bool) {
	if t == durationType {
		return "i64", strconv.FormatInt(v.Int(), 10), true
	}
	switch t.Kind() {
	case reflect.Bool:
		return "bool", strconv.FormatBool(v.Bool()), true
	case reflect.Int, reflect.Int64:
		return "i64", intLit(v.Int(), 64), true
	case reflect.Int32:
		return "i32", intLit(v.Int(), 32), true
	case reflect.Int16:
		return "i16", strconv.FormatInt(v.Int(), 10), true
	case reflect.Int8:
		return "i8", strconv.FormatInt(v.Int(), 10), true
	case reflect.Uint, reflect.Uint64, reflect.Uintptr:
		if v.Uint() == math.MaxUint64 {
			return "u64", "u64::MAX", true
		}
		return "u64", strconv.FormatUint(v.Uint(), 10), true
	case reflect.Uint32:
		return "u32", strconv.FormatUint(v.Uint(), 10), true
	case reflect.Uint16:
		return "u16", strconv.FormatUint(v.Uint(), 10), true
	case reflect.Uint8:
		return "u8", strconv.FormatUint(v.Uint(), 10), true
	case reflect.Float64:
		return "f64", floatLit(v.Float()), true
	case reflect.Float32:
		return "f32", floatLit(v.Float()) + "_f32", true
	case reflect.String:
		return "String", rustStr(v.String()) + ".to_owned()", true
	}
	return "", "", false
}

func intLit(x int64, bits int) string {
	if bits == 64 && x == math.MinInt64 {
		return "i64::MIN"
	}
	if bits == 64 && x == math.MaxInt64 {
		return "i64::MAX"
	}
	return strconv.FormatInt(x, 10)
}

func floatLit(f float64) string {
	s := strconv.FormatFloat(f, 'g', -1, 64)
	if !strings.ContainsAny(s, ".eEn") {
		s += ".0"
	}
	return s
}

package main

// rsgen -protos rewrites internal/protos/protos_list.go: the util/dbterror prototype variables
// by name, so the generator can read their run-time values.

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/token"
	"os"
	"path/filepath"
)

func writeProtosList(tidbDir string) {
	var b bytes.Buffer
	b.WriteString("// Code generated by rsgen -protos. DO NOT EDIT.\n\npackage protos\n\nimport (\n\t\"github.com/pingcap/errors\"\n\t\"github.com/pingcap/tidb/pkg/util/dbterror\"\n\t\"github.com/pingcap/tidb/pkg/util/dbterror/exeerrors\"\n\t\"github.com/pingcap/tidb/pkg/util/dbterror/plannererrors\"\n)\n\n")
	b.WriteString("// Vars are the error prototypes of pkg/util/dbterror (and subpackages) by \"<go file>:<name>\".\nvar Vars = map[string]*errors.Error{\n")
	for _, f := range []struct{ dir, file, pkg, goPath string }{
		{"pkg/util/dbterror", "ddl_terror.go", "dbterror", "pkg/util/dbterror/ddl_terror.go"},
		{"pkg/util/dbterror/exeerrors", "errors.go", "exeerrors", "pkg/util/dbterror/exeerrors/errors.go"},
		{"pkg/util/dbterror/plannererrors", "planner_terror.go", "plannererrors", "pkg/util/dbterror/plannererrors/planner_terror.go"},
	} {
		p := load(filepath.Join(tidbDir, f.dir))
		for _, d := range p.files[f.file].Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.VAR {
				continue
			}
			for _, s := range gd.Specs {
				vs := s.(*ast.ValueSpec)
				for i, id := range vs.Names {
					if !isProto(vs.Values[i]) {
						continue
					}
					fmt.Fprintf(&b, "\t%q: %s.%s,\n", f.goPath+":"+id.Name, f.pkg, id.Name)
				}
			}
		}
	}
	b.WriteString("}\n")
	if err := os.WriteFile("internal/protos/protos_list.go", b.Bytes(), 0o644); err != nil {
		panic(err)
	}
	fmt.Fprintln(os.Stderr, "rsgen: wrote internal/protos/protos_list.go")
}

// isProto: the value is ClassX.NewStd(...) / NewStdErr(...).
func isProto(x ast.Expr) bool {
	call, ok := x.(*ast.CallExpr)
	if !ok {
		return false
	}
	sel, ok := call.Fun.(*ast.SelectorExpr)
	return ok && (sel.Sel.Name == "NewStd" || sel.Sel.Name == "NewStdErr")
}

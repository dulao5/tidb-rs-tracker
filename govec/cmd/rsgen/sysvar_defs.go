// sysvarDefsHandWritten are Def* constants that tidb-rs declares by hand in
// variable/tidb_vars.rs (D05.1, with the Rust types their users need): not generated.
var sysvarDefsHandWritten = map[string]bool{
	"DefTiDBEnableNoopFuncs": true, "DefTiDBAllowMPPExecution": true, "DefTiDBForeignKeyChecks": true,
	"DefTiDBRowFormatV2": true, "DefTiDBDDLReorgWorkerCount": true, "DefTiDBDDLReorgBatchSize": true,
	"DefTiDBDDLFlashbackConcurrency": true, "DefTiDBDDLErrorCountLimit": true,
	"DefTiDBMaxDeltaSchemaCount": true, "DefTimestampFloat": true, "DefTiDBMemQuotaQuery": true,
	"DefTiDBEnableAutoAnalyze": true, "DefTiDBEnableAutoAnalyzePriorityQueue": true,
	"DefTiDBMaxDistTaskNodes": true, "DefTiDBMPPStoreFailTTL": true, "DefTiDBGOGCTunerThreshold": true,
	"DefTiDBGOGCMaxValue": true, "DefTiDBGOGCMinValue": true, "DefRuntimeFilterType": true,
	"DefRuntimeFilterMode": true,
}

// genSysvarDefs writes variable/tidb_defs.rs: the exported Def* constants of package
// variable whose value the type checker resolves (literals and expressions over the
// standard library), with Go's type: untyped integers as i64, untyped floats as f64,
// time.Duration as i64 nanoseconds. The session hooks (D05.2) pass them as defaults.
func genSysvarDefs(outDir string) {
	vdir := filepath.Join(modDir("github.com/pingcap/tidb"), "pkg", "sessionctx", "variable")
	p := load(vdir)
	type def struct{ name, rt, val, file string }
	var defs []def
	seen := map[string]bool{}
	for id, obj := range p.info.Defs {
		c, ok := obj.(*types.Const)
		if !ok || c.Parent() != c.Pkg().Scope() || !strings.HasPrefix(c.Name(), "Def") || !c.Exported() {
			continue
		}
		if sysvarDefsHandWritten[c.Name()] || seen[c.Name()] || c.Val().Kind() == constant.Unknown {
			continue
		}
		rt, val, ok := rustConst(c)
		if !ok {
			continue
		}
		seen[c.Name()] = true
		defs = append(defs, def{c.Name(), rt, val, filepath.Base(p.fset.Position(id.Pos()).Filename)})
	}
	sort.Slice(defs, func(i, j int) bool { return defs[i].name < defs[j].name })
	var b strings.Builder
	b.WriteString("// Code generated by tidb-rs-tracker govec/cmd/rsgen from TiDB v8.5.8. DO NOT EDIT.\n")
	b.WriteString("// Regenerate: (cd govec && go run ./cmd/rsgen -sysvar-defs <tidb-rs>/crates/sessionctx/src), then cargo fmt\n")
	b.WriteString("//\n//! The `Def*` constants of pkg/sessionctx/variable (tidb_vars.go and others) that the\n")
	b.WriteString("//! session hooks pass as defaults (D05.2). Go's types: untyped integers are `i64`,\n")
	b.WriteString("//! untyped floats `f64`, `time.Duration` nanoseconds `i64`. The ones D05.1 declares by\n")
	b.WriteString("//! hand are in `tidb_vars.rs`.\n\n#![allow(non_upper_case_globals)]\n#![allow(clippy::excessive_precision)]\n\n")
	for _, d := range defs {
		fmt.Fprintf(&b, "/// Go: `%s` (%s).\npub const %s: %s = %s;\n", d.name, d.file, d.name, d.rt, d.val)
	}
	path := filepath.Join(outDir, "variable", "tidb_defs.rs")
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
	fmt.Fprintf(os.Stderr, "rsgen: %s (%d constants)\n", path, len(defs))
}

func rustConst(c *types.Const) (rt, val string, ok bool) {
	t := c.Type()
	v := c.Val()
	if named, isNamed := t.(*types.Named); isNamed {
		if named.Obj().Pkg() != nil && named.Obj().Pkg().Path() == "time" && named.Obj().Name() == "Duration" {
			i, exact := constant.Int64Val(v)
			if !exact {
				return "", "", false
			}
			return "i64", strconv.FormatInt(i, 10), true
		}
		return "", "", false
	}
	bt, isBasic := t.(*types.Basic)
	if !isBasic {
		return "", "", false
	}
	switch bt.Kind() {
	case types.UntypedBool, types.Bool:
		return "bool", strconv.FormatBool(constant.BoolVal(v)), true
	case types.UntypedString, types.String:
		return "&str", strconv.Quote(constant.StringVal(v)), true
	case types.UntypedFloat, types.Float64:
		f, _ := constant.Float64Val(v)
		s := strconv.FormatFloat(f, 'g', -1, 64)
		if !strings.ContainsAny(s, ".eE") {
			s += ".0"
		}
		return "f64", s, true
	}
	ints := map[types.BasicKind]string{
		types.UntypedInt: "i64", types.Int: "i64", types.Int64: "i64", types.Int32: "i32",
		types.Uint: "u64", types.Uint64: "u64", types.Uint32: "u32", types.Uint8: "u8", types.Int8: "i8",
		types.Int16: "i16", types.Uint16: "u16",
	}
	r, ok := ints[bt.Kind()]
	if !ok {
		return "", "", false
	}
	if strings.HasPrefix(r, "u") {
		u, exact := constant.Uint64Val(v)
		if !exact {
			return "", "", false
		}
		return r, strconv.FormatUint(u, 10), true
	}
	i, exact := constant.Int64Val(v)
	if !exact {
		return "", "", false
	}
	return r, strconv.FormatInt(i, 10), true
}

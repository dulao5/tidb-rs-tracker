// domainName overrides the govec domain named in the generated file header.
var domainName string

func modDir(mod string) string {
	b, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", mod).Output()
	if err != nil {
		panic(fmt.Sprintf("go list -m %s: %v", mod, err))
	}
	return strings.TrimSpace(string(b))
}

// pkg is one type-checked Go package (non-test files).
type pkg struct {
	dir   string
	fset  *token.FileSet
	files map[string]*ast.File // base name -> file
	info  *types.Info
}

type nopImporter struct{}

func (nopImporter) Import(path string) (*types.Package, error) {
	// Standard library imports resolve; everything else is stubbed, its
	// expressions are left untyped (errors ignored).
	if !strings.Contains(path, ".") {
		return importer.Default().Import(path)
	}
	return nil, fmt.Errorf("stub")
}

func load(dir string) *pkg {
	fset := token.NewFileSet()
	ents, err := os.ReadDir(dir)
	if err != nil {
		panic(err)
	}
	p := &pkg{dir: dir, fset: fset, files: map[string]*ast.File{}}
	var files []*ast.File
	for _, e := range ents {
		n := e.Name()
		if !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, n), nil, parser.ParseComments)
		if err != nil {
			panic(err)
		}
		p.files[n] = f
		files = append(files, f)
	}
	p.info = &types.Info{
		Types: map[ast.Expr]types.TypeAndValue{},
		Defs:  map[*ast.Ident]types.Object{},
		Uses:  map[*ast.Ident]types.Object{},
	}
	conf := types.Config{Importer: nopImporter{}, Error: func(error) {}}
	conf.Check("p", fset, files, p.info)
	return p
}

// ---------------------------------------------------------------- Rust output

type emitter struct {
	buf bytes.Buffer
}

func (e *emitter) p(format string, args ...any) { fmt.Fprintf(&e.buf, format, args...) }

func (e *emitter) header(goFiles ...string) {
	e.p("// Code generated by tidb-rs-tracker govec/cmd/rsgen from TiDB v8.5.8. DO NOT EDIT.\n")
	if domainName == "model" {
		e.p("// Regenerate: (cd govec && go run ./cmd/rsgen -model <tidb-rs>/crates/model/src), then cargo fmt\n")
	} else {
		e.p("// Regenerate: (cd govec && go run ./cmd/rsgen -out <tidb-rs>/crates/base/src)\n")
	}
	domain := "base"
	for _, f := range goFiles {
		if strings.HasPrefix(f, "pkg/config/") {
			domain = "config"
		}
	}
	if domainName != "" {
		domain = domainName
	}
	e.p("// Verified by the govec domain %q (tests/govec_%s.rs).\n\n", domain, domain)
	for _, f := range goFiles {
		e.p("//! go-file: %s\n", f)
	}
	e.p("\n// Generated data keeps Go's identifiers (mapping rule M-GONAME).\n#![allow(non_upper_case_globals)]\n\n")
}

func (e *emitter) write(rel string) {
	path := filepath.Join(*out, rel)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		panic(err)
	}
	if err := os.WriteFile(path, e.buf.Bytes(), 0o644); err != nil {
		panic(err)
	}
	fmt.Fprintf(os.Stderr, "rsgen: wrote %s (%d bytes)\n", rel, e.buf.Len())
}

// rustDoc renders a Go comment group as Rust doc lines.
func rustDoc(e *emitter, indent string, cg *ast.CommentGroup) {
	if cg == nil {
		return
	}
	for _, l := range strings.Split(strings.TrimRight(cg.Text(), "\n"), "\n") {
		if strings.HasPrefix(l, "    ") || strings.HasPrefix(l, "\t") {
			l = "`" + strings.TrimSpace(l) + "`" // avoid rustdoc code blocks
		}
		if l == "" {
			e.p("%s///\n", indent)
		} else {
			e.p("%s/// %s\n", indent, l)
		}
	}
}

func rustStr(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\t':
			b.WriteString(`\t`)
		case r == '\r':
			b.WriteString(`\r`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u{%x}`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// rustType maps a Go constant type to Rust. Named types keep their name (the
// Rust port defines them as newtypes, see mysql/const.rs etc.).
func rustType(t types.Type, untyped string) string {
	switch tt := t.(type) {
	case *types.Named:
		return tt.Obj().Name()
	case *types.Basic:
		switch tt.Kind() {
		case types.Uint8:
			return "u8"
		case types.Uint16:
			return "u16"
		case types.Uint32:
			return "u32"
		case types.Uint64:
			return "u64"
		case types.Uint:
			return "usize"
		case types.Int8:
			return "i8"
		case types.Int16:
			return "i16"
		case types.Int32:
			return "i32"
		case types.Int64:
			return "i64"
		case types.Int:
			return "isize"
		case types.Float64:
			return "f64"
		case types.String:
			return "&str"
		case types.Bool:
			return "bool"
		case types.UntypedInt, types.UntypedRune:
			return untyped
		case types.UntypedString:
			return "&str"
		case types.UntypedFloat:
			return "f64"
		case types.UntypedBool:
			return "bool"
		}
	}
	panic(fmt.Sprintf("rsgen: unsupported constant type %v", t))
}

var newtypes = map[string]bool{} // filled by constBlock: named types seen

func rustValue(v constant.Value, rt string) string {
	switch v.Kind() {
	case constant.String:
		if stringNewtypes[rt] {
			return rt + "(Cow::Borrowed(" + rustStr(constant.StringVal(v)) + "))"
		}
		return rustStr(constant.StringVal(v))
	case constant.Bool:
		return strconv.FormatBool(constant.BoolVal(v))
	case constant.Float:
		f, _ := constant.Float64Val(v)
		s := strconv.FormatFloat(f, 'g', -1, 64)
		if !strings.ContainsAny(s, ".eE") {
			s += ".0"
		}
		return s
	case constant.Int:
		s := v.ExactString()
		if newtypes[rt] && rt != "Duration" {
			return rt + "(" + s + ")"
		}
		return s
	}
	panic(fmt.Sprintf("rsgen: unsupported constant value %v", v))
}

// constBlock emits every package-level constant declared in the file, in
// source order. untyped: Rust type for untyped integer constants of this
// file; override: per-name Rust type. skip: names not emitted (ported by hand).
func constBlock(e *emitter, p *pkg, file, untyped string, override map[string]string, skip map[string]bool) int {
	f := p.files[file]
	n := 0
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		if gd.Lparen.IsValid() && gd.Doc != nil {
			e.p("\n")
			for _, l := range strings.Split(strings.TrimRight(gd.Doc.Text(), "\n"), "\n") {
				e.p("// %s\n", l)
			}
			e.p("\n")
		}
		for _, s := range gd.Specs {
			vs := s.(*ast.ValueSpec)
			for _, id := range vs.Names {
				if id.Name == "_" || skip[id.Name] {
					continue
				}
				obj, ok := p.info.Defs[id].(*types.Const)
				if !ok || obj.Val().Kind() == constant.Unknown {
					panic(fmt.Sprintf("rsgen: %s: constant %s not evaluated", file, id.Name))
				}
				rt := override[id.Name]
				if rt == "" {
					rt = rustType(obj.Type(), untyped)
				}
				if nt, ok := obj.Type().(*types.Named); ok {
					newtypes[nt.Obj().Name()] = true
				}
				doc := vs.Doc
				if doc == nil && !gd.Lparen.IsValid() {
					doc = gd.Doc
				}
				rustDoc(e, "", doc)
				if vs.Comment != nil {
					rustDoc(e, "", vs.Comment)
				}
				typ := rt
				vis := "pub"
				if !id.IsExported() {
					vis = "pub(crate)"
				}
				e.p("%s const %s: %s = %s;\n", vis, id.Name, typ, rustValue(obj.Val(), rt))
				n++
			}
		}
	}
	return n
}

// ---------------------------------------------------------------- map literals

// findVar returns the composite literal assigned to package-level var name.
func findVar(p *pkg, file, name string) (*ast.ValueSpec, *ast.CompositeLit) {
	for _, d := range p.files[file].Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.VAR {
			continue
		}
		for _, s := range gd.Specs {
			vs := s.(*ast.ValueSpec)
			for i, id := range vs.Names {
				if id.Name == name {
					cl, ok := vs.Values[i].(*ast.CompositeLit)
					if !ok {
						panic("rsgen: " + name + " is not a composite literal")
					}
					if vs.Doc == nil {
						vs.Doc = gd.Doc
					}
					return vs, cl
				}
			}
		}
	}
	panic("rsgen: var " + name + " not found in " + file)
}

type kv struct {
	sortKey string // for sorting: zero-padded int or string
	key     string // Rust expression
	val     string // Rust expression
}

// expr renders a key/value expression: an identifier (constant name, kept),
// a literal or constant expression (value), Message("...", nil|[]int{..}),
// or a slice/composite of those.
func expr(p *pkg, x ast.Expr, rt string) string {
	switch t := x.(type) {
	case *ast.Ident:
		if t.Name == "nil" {
			return "&[]"
		}
		return t.Name
	case *ast.SelectorExpr: // other package's constant, e.g. errno.ErrX: keep the name
		return t.Sel.Name
	case *ast.CallExpr:
		fn := ""
		switch f := t.Fun.(type) {
		case *ast.Ident:
			fn = f.Name
		case *ast.SelectorExpr:
			fn = f.Sel.Name
		}
		if fn == "Message" && len(t.Args) == 2 {
			return fmt.Sprintf("ErrMessage::new(%s, %s)", expr(p, t.Args[0], "&str"), expr(p, t.Args[1], ""))
		}
	case *ast.CompositeLit:
		if structFields != nil && t.Type == nil {
			var parts []string
			for i, el := range t.Elts {
				parts = append(parts, structFields[i]+": "+expr(p, el, structTypes[i]))
			}
			return structName + " { " + strings.Join(parts, ", ") + " }"
		}
		var parts []string
		for _, el := range t.Elts {
			parts = append(parts, expr(p, el, ""))
		}
		if _, isArr := t.Type.(*ast.ArrayType); isArr || t.Type == nil || isNamed(t.Type) {
			return "&[" + strings.Join(parts, ", ") + "]"
		}
	}
	if tv, ok := p.info.Types[x]; ok && tv.Value != nil {
		return rustValue(tv.Value, rt)
	}
	panic(fmt.Sprintf("rsgen: unsupported expression %T at %v", x, p.fset.Position(x.Pos())))
}

// Struct literal values of the map being generated (goMap's caller sets them).
var (
	structName   string
	structFields []string
	structTypes  []string
)

func isNamed(x ast.Expr) bool { _, ok := x.(*ast.Ident); return ok }

func sortKey(p *pkg, x ast.Expr, resolve func(string) (constant.Value, bool)) string {
	var v constant.Value
	if tv, ok := p.info.Types[x]; ok && tv.Value != nil {
		v = tv.Value
	} else if sel, ok := x.(*ast.SelectorExpr); ok && resolve != nil {
		if rv, ok := resolve(sel.Sel.Name); ok {
			v = rv
		}
	}
	if v == nil {
		panic(fmt.Sprintf("rsgen: map key not constant at %v", p.fset.Position(x.Pos())))
	}
	if v.Kind() == constant.String {
		return constant.StringVal(v)
	}
	i, _ := constant.Int64Val(v)
	return fmt.Sprintf("%020d", i+1<<62)
}

// goMap emits `pub static <name>: GoMap<K, V>` sorted by key value.
func goMap(e *emitter, p *pkg, file, name, kt, vt string, resolve func(string) (constant.Value, bool)) int {
	vs, cl := findVar(p, file, name)
	var kvs []kv
	seen := map[string]string{}
	for _, el := range cl.Elts {
		ke := el.(*ast.KeyValueExpr)
		sk := sortKey(p, ke.Key, resolve)
		k := expr(p, ke.Key, kt)
		if prev, dup := seen[sk]; dup {
			panic(fmt.Sprintf("rsgen: %s: duplicate key %s / %s", name, prev, k))
		}
		seen[sk] = k
		kvs = append(kvs, kv{sk, k, expr(p, ke.Value, vt)})
	}
	sort.Slice(kvs, func(i, j int) bool { return kvs[i].sortKey < kvs[j].sortKey })
	rustDoc(e, "", vs.Doc)
	e.p("///\n/// Go `map` literal; entries sorted by key (generated).\n")
	e.p("pub static %s: GoMap<%s, %s> = GoMap::new(&[\n", name, kt, vt)
	for _, x := range kvs {
		e.p("    (%s, %s),\n", x.key, x.val)
	}
	e.p("]);\n")
	return len(kvs)
}

// goSlice emits `pub static <name>: &[T]` from a slice literal, in source order.
func goSlice(e *emitter, p *pkg, file, name, et string) int {
	vs, cl := findVar(p, file, name)
	rustDoc(e, "", vs.Doc)
	e.p("pub static %s: &[%s] = &[\n", name, et)
	for _, el := range cl.Elts {
		e.p("    %s,\n", expr(p, el, et))
	}
	e.p("];\n")
	return len(cl.Elts)
}

// ---------------------------------------------------------------- jobs

type mapJob struct {
	name, kt, vt string
	// struct-valued maps: Rust struct name, field names and types
	sname   string
	sfields []string
	stypes  []string
}

type sliceJob struct{ name, et string }

type fileJob struct {
	goFile   string // under the package dir
	rs       string // output, under -out
	uses     string // Rust `use` lines
	untyped  string // Rust type of untyped integer constants
	override map[string]string
	consts   bool
	maps     []mapJob
	slices   []sliceJob
}

func runFile(p *pkg, goPath string, j fileJob) {
	e := &emitter{}
	e.header(goPath)
	e.p("%s\n", j.uses)
	nc, nm := 0, 0
	if j.consts {
		nc = constBlock(e, p, j.goFile, j.untyped, j.override, nil)
	}
	for _, m := range j.maps {
		e.p("\n")
		structName, structFields, structTypes = m.sname, m.sfields, m.stypes
		nm += goMap(e, p, j.goFile, m.name, m.kt, m.vt, nil)
		structName, structFields, structTypes = "", nil, nil
	}
	for _, sl := range j.slices {
		e.p("\n")
		nm += goSlice(e, p, j.goFile, sl.name, sl.et)
	}
	e.write(j.rs)
	fmt.Fprintf(os.Stderr, "  %d constants, %d map/slice entries\n", nc, nm)
}


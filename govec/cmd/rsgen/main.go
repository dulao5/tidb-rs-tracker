// Command rsgen generates the data tables of tidb-rs porting block D00.2
// (constants, error code / message / SQLSTATE maps, charset tables) as Rust
// source, mechanically from the Go source of TiDB v8.5.8.
//
// Only data is generated, never logic: the functions of the block are ported
// by hand. Names, order and doc comments come from the Go AST; constant values
// come from go/types (the files are type-checked with imports stubbed out, so
// only self-contained constant expressions are evaluated, which is all these
// tables use). Every generated table is cross-checked at run time by the govec
// domain "base" (vectors dump Go's actual map contents), so a generator bug
// shows up as a vector mismatch in tidb-rs.
//
//	go run ./cmd/rsgen -out ../../tidb-rs/crates/base/src
//
// The TiDB source is located with `go list -m` (the module versions pinned in
// govec/go.mod), so the output does not depend on a local checkout.

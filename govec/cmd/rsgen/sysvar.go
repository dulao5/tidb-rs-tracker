package main

// System variable table of block D05.1 (N8 §3.1): the static fields of every
// *SysVar in defaultSysVars (sysvar.go) and noopSysVars (noop.go), in source
// order, with the Go line and the name constant of each entry. Order, line and
// constant name come from the AST; the field values are the ones the running
// registry holds after init (variable.GetSysVar), so computed defaults
// (strconv.Itoa(Def...), mysql.ServerVersion, ...) are their evaluated form.
// Entries whose Value expression is not a compile-time constant are marked
// `computed` so the Rust side must decide them by hand (runtime.GOOS etc.).
// Hooks are logic and are never generated: the table only records which hooks
// Go has, and the tidb-rs registry checks that its hand-written hooks match.
//
//	go run ./cmd/rsgen -sysvar <tidb-rs>/crates/sessionctx/src

import (
	"fmt"
	"go/ast"
	"go/constant"
	"os"
	"path/filepath"
	"reflect"
	"strings"

	"github.com/pingcap/tidb/pkg/sessionctx/variable"
)

type sysvarEntry struct {
	file     string
	line     int
	ident    string // name expression as written (constant identifier or literal)
	name     string
	computed string // Value expression when it is not a constant
}

func sysvarEntries(p *pkg, file, varName string) []sysvarEntry {
	_, lit := findVar(p, file, varName)
	if lit == nil {
		panic("rsgen: " + varName + " not found in " + file)
	}
	var out []sysvarEntry
	for _, el := range lit.Elts {
		cl, ok := el.(*ast.CompositeLit)
		if !ok {
			if u, ok2 := el.(*ast.UnaryExpr); ok2 {
				cl, ok = u.X.(*ast.CompositeLit)
			}
		}
		if !ok {
			panic(fmt.Sprintf("rsgen: %s element %T", varName, el))
		}
		e := sysvarEntry{file: file, line: p.fset.Position(cl.Pos()).Line}
		var valueExpr ast.Expr
		for _, f := range cl.Elts {
			kv := f.(*ast.KeyValueExpr)
			switch kv.Key.(*ast.Ident).Name {
			case "Name":
				tv := p.info.Types[kv.Value]
				if tv.Value == nil || tv.Value.Kind() != constant.String {
					panic(fmt.Sprintf("rsgen: %s:%d Name is not a string constant", file, e.line))
				}
				e.name = constant.StringVal(tv.Value)
				e.ident = exprString(p, kv.Value)
			case "Value":
				valueExpr = kv.Value
			}
		}
		if valueExpr != nil {
			// Function calls of constants (strconv.Itoa(Def...), BoolToOnOff(...)) are
			// deterministic and kept as their evaluated value; only values that depend on
			// the build target or the loaded config are marked for the Rust side.
			if tv := p.info.Types[valueExpr]; tv.Value == nil {
				if x := exprString(p, valueExpr); strings.Contains(x, "runtime.") || strings.Contains(x, "config.GetGlobalConfig") {
					e.computed = x
				}
			}
		}
		out = append(out, e)
	}
	return out
}

func exprString(p *pkg, x ast.Expr) string {
	start := p.fset.Position(x.Pos()).Offset
	end := p.fset.Position(x.End()).Offset
	f := p.fset.File(x.Pos())
	src := p.srcOf(f.Name())
	return strings.Join(strings.Fields(string(src[start:end])), " ")
}

var scopeNames = []struct {
	f variable.ScopeFlag
	n string
}{{variable.ScopeGlobal, "ScopeGlobal"}, {variable.ScopeSession, "ScopeSession"}, {variable.ScopeInstance, "ScopeInstance"}}

func rustScope(s variable.ScopeFlag) string {
	if s == variable.ScopeNone {
		return "ScopeNone"
	}
	var parts []string
	for _, sn := range scopeNames {
		if s&sn.f != 0 {
			parts = append(parts, sn.n)
		}
	}
	if len(parts) == 1 {
		return parts[0]
	}
	return "ScopeFlag(" + strings.Join(func() []string {
		var r []string
		for _, x := range parts {
			r = append(r, x+".0")
		}
		return r
	}(), " | ") + ")"
}

var typeNames = map[variable.TypeFlag]string{
	variable.TypeStr: "TypeStr", variable.TypeBool: "TypeBool", variable.TypeInt: "TypeInt",
	variable.TypeEnum: "TypeEnum", variable.TypeFloat: "TypeFloat", variable.TypeUnsigned: "TypeUnsigned",
	variable.TypeTime: "TypeTime", variable.TypeDuration: "TypeDuration",
}

func rustStrSlice(ss []string) string {
	if len(ss) == 0 {
		return "&[]"
	}
	var parts []string
	for _, s := range ss {
		parts = append(parts, rustStr(s))
	}
	return "&[" + strings.Join(parts, ", ") + "]"
}

func genSysvarTable(outDir string) {
	vdir := filepath.Join(modDir("github.com/pingcap/tidb"), "pkg", "sessionctx", "variable")
	p := load(vdir)
	var entries []sysvarEntry
	entries = append(entries, sysvarEntries(p, "sysvar.go", "defaultSysVars")...)
	nDefault := len(entries)
	entries = append(entries, sysvarEntries(p, "noop.go", "noopSysVars")...)

	var e emitter
	e.p("// Code generated by tidb-rs-tracker govec/cmd/rsgen from TiDB v8.5.8. DO NOT EDIT.\n")
	e.p("// Regenerate: (cd govec && go run ./cmd/rsgen -sysvar <tidb-rs>/crates/sessionctx/src)\n")
	e.p("// Cross-checked by the govec domain \"sysvar\" (op `registry`).\n")
	e.p("//\n// go-file: pkg/sessionctx/variable/sysvar.go defaultSysVars, pkg/sessionctx/variable/noop.go noopSysVars\n")
	e.p("// Static fields only (N8 §3.1, option c): the hooks are hand-written (hooks.rs);\n")
	e.p("// `hooks` records which hooks Go has, so the registry can check it has the same.\n\n")
	e.p("use super::variable::*;\n\n")
	e.p("/// Number of entries of `defaultSysVars`; the rest of [`SYSVAR_DATA`] is `noopSysVars`.\n")
	e.p("pub const DEFAULT_SYSVAR_COUNT: usize = %d;\n\n", nDefault)
	e.p("#[rustfmt::skip]\npub static SYSVAR_DATA: &[SysVarData] = &[\n")
	seen := map[string]bool{}
	for _, en := range entries {
		if seen[en.name] {
			panic("rsgen: duplicate sysvar " + en.name)
		}
		seen[en.name] = true
		sv := variable.GetSysVar(en.name)
		if sv == nil {
			panic("rsgen: sysvar not registered: " + en.name)
		}
		rv := reflect.ValueOf(sv).Elem()
		skipInit := rv.FieldByName("skipInit").Bool()
		var hooks []string
		for _, h := range []struct{ f, n string }{
			{"Validation", "HOOK_VALIDATION"}, {"SetSession", "HOOK_SET_SESSION"}, {"SetGlobal", "HOOK_SET_GLOBAL"},
			{"GetSession", "HOOK_GET_SESSION"}, {"GetGlobal", "HOOK_GET_GLOBAL"}, {"GetStateValue", "HOOK_GET_STATE_VALUE"},
			{"RequireDynamicPrivileges", "HOOK_REQUIRE_DYNAMIC_PRIVILEGES"},
		} {
			if !rv.FieldByName(h.f).IsNil() {
				hooks = append(hooks, h.n)
			}
		}
		hookExpr := "0"
		if len(hooks) > 0 {
			hookExpr = strings.Join(hooks, " | ")
		}
		var flags []string
		for _, fl := range []struct {
			on bool
			n  string
		}{
			{sv.AutoConvertNegativeBool, "FLAG_AUTO_CONVERT_NEGATIVE_BOOL"}, {sv.ReadOnly, "FLAG_READ_ONLY"},
			{sv.AllowEmpty, "FLAG_ALLOW_EMPTY"}, {sv.AllowEmptyAll, "FLAG_ALLOW_EMPTY_ALL"},
			{sv.AllowAutoValue, "FLAG_ALLOW_AUTO_VALUE"}, {sv.IsHintUpdatableVerified, "FLAG_HINT_UPDATABLE_VERIFIED"},
			{sv.Hidden, "FLAG_HIDDEN"}, {sv.Depended, "FLAG_DEPENDED"}, {skipInit, "FLAG_SKIP_INIT"}, {sv.IsNoop, "FLAG_IS_NOOP"},
		} {
			if fl.on {
				flags = append(flags, fl.n)
			}
		}
		flagExpr := "0"
		if len(flags) > 0 {
			flagExpr = strings.Join(flags, " | ")
		}
		computed := "None"
		if en.computed != "" {
			computed = "Some(" + rustStr(en.computed) + ")"
		}
		e.p("    // go: %s:L%d %s\n", en.file, en.line, en.ident)
		e.p("    SysVarData { go_file: %s, go_line: %d, scope: %s, name: %s, value: %s, computed: %s, typ: %s, min_value: %d, max_value: %d, possible_values: %s, aliases: %s, global_config_name: %s, flags: %s, hooks: %s },\n",
			rustStr(en.file), en.line, rustScope(sv.Scope), rustStr(sv.Name), rustStr(sv.Value), computed,
			rustTypeFlag(sv.Type), sv.MinValue, sv.MaxValue, rustStrSlice(sv.PossibleValues), rustStrSlice(sv.Aliases),
			rustStr(sv.GlobalConfigName), flagExpr, hookExpr)
	}
	e.p("];\n")
	if got := len(variable.GetSysVars()); got != len(entries) {
		panic(fmt.Sprintf("rsgen: registry has %d sysvars, the two tables %d", got, len(entries)))
	}
	saved := *out
	*out = outDir
	e.write("variable/sysvar_data.rs")
	*out = saved
}

var srcCache = map[string][]byte{}

func (p *pkg) srcOf(path string) []byte {
	if b, ok := srcCache[path]; ok {
		return b
	}
	b, err := os.ReadFile(path)
	if err != nil {
		panic(err)
	}
	srcCache[path] = b
	return b
}

// rustTypeFlag: the TypeFlag constant, or TypeFlag(n) for a value no constant names (the
// zero value of an entry without Type, which ValidateFromType treats as a string).
func rustTypeFlag(t variable.TypeFlag) string {
	if n, ok := typeNames[t]; ok {
		return n
	}
	return fmt.Sprintf("TypeFlag(%d)", t)
}
